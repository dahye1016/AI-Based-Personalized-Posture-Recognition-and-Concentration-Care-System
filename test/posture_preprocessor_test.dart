PosturePreprocessor _load() {
  final json = jsonDecode(File('assets/model/norm_stats.json').readAsStringSync())
      as Map<String, dynamic>;
  return PosturePreprocessor.fromJson(json);
}

void main() {
  test('json 의 라벨 순서가 앱 순서와 같다', () {
    final json = jsonDecode(File('assets/model/norm_stats.json').readAsStringSync())
        as Map<String, dynamic>;
    expect(json['label_order'], kExpectedLabelOrder);
  });

  test('입력은 64개, 뒤 32개는 0 패딩', () {
    final pre = _load();
    final x = pre.toInput(_cases.first.channels);
    expect(x.length, 64);
    expect(x.sublist(32).every((v) => v == 0), isTrue);
  });

  for (final c in _cases) {
    test('전처리가 파이썬과 일치: ${c.label}', () {
      final x = _load().toInput(c.channels);
      for (var i = 0; i < 64; i++) {
        expect(x[i], closeTo(c.input[i], 1e-3), reason: 'index $i');
      }
    });
  }

  test('argmax', () {
    expect(PosturePreprocessor.argmax([0.1, 2.0, -1.0, 1.9]), 1);
  });

  test('다수결 안정화: 튀는 값 한 개는 무시', () {
    final s = MajoritySmoother(window: 5);
    for (var i = 0; i < 4; i++) {
      s.add(1);
    }
    expect(s.add(2), 1);
  });
}
