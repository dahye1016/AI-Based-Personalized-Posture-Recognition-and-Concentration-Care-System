"""[LEGACY / BASELINE 후보] 규칙 기반 6채널 자세 판정 (구 아키텍처).

⚠️ 현재 서버 파이프라인에서는 호출되지 않는다.
   자세 판정은 앱(TFLite, 7클래스)이 온디바이스로 수행한다.

보존 이유:
  향후 CNN 추론 결과를 검증하는 baseline(규칙 기반 대조군)으로 재활용할 수 있다.
  삭제하지 말 것. 다만 그대로는 재사용할 수 없고 아래 gap 을 메우는 어댑터가 필요하다.

━━━ baseline 으로 재사용하려면 메워야 할 gap ━━━

1. 입력 차원 (6채널 → 64채널)
   이 로직은 FSR 6개(앞/중/뒤 × 좌/우)를 하드코딩으로 받는다.
   신규 하드웨어는 32ch 매트 2장 = 64채널이다.
   → 64채널에서 6개 대표값을 뽑는 집계(영역 평균 등) 정의가 필요하다.

2. 출력 클래스 매핑 (4종 문자열 → 7종 정수 0~6)
   이 로직의 출력은 "바른자세/거북목/기대기/다리꼬기" 4종 한글 문자열이다.
   신규 표준은 정수 0~6 (constants.POSTURE_LABELS) 7종이다.
   → 문자열 → 정수 라벨 변환 매핑이 필요하다.

3. 좌우 구분 없음 (★ 직접 비교 불가)
   현재 규칙은 4종이라 7종과 1:1 비교가 불가능하다. 핵심은 좌/우 구분이 없다는 점:
     - "다리꼬기"(4종)  →  7종의 3(오른다리 꼬기) / 4(왼다리 꼬기)로 갈린다.
     - "기대기"(4종)    →  7종의 5(오른쪽 기대기) / 6(왼쪽 기대기)로 갈린다.
   따라서 이 규칙을 baseline 으로 쓰려면, CNN 의 7종 출력을 4종 축으로 내려
   비교해야 한다. 즉 3/4 → 하나(다리꼬기), 5/6 → 하나(기대기)로 묶는
   "7종 → 4종 축소 어댑터"가 있어야 규칙 baseline 과 대조가 가능하다.
   (반대로 이 규칙을 7종으로 끌어올리는 것은 좌우 정보가 없어 불가능하다.)
"""


def classify_posture(s1, s2, s3, s4, s5, s6):
    """
    6개 센서값을 받아서 자세를 판정하는 함수
    
    센서 위치:
    s1: 앞 왼쪽   s2: 앞 오른쪽
    s3: 중간 왼쪽 s4: 중간 오른쪽
    s5: 뒤 왼쪽   s6: 뒤 오른쪽
    """

    # 앞/뒤/좌/우 평균값 계산
    front_avg = (s1 + s2) / 2   # 앞쪽 평균
    back_avg  = (s5 + s6) / 2   # 뒤쪽 평균
    left_avg  = (s1 + s3 + s5) / 3  # 왼쪽 평균
    right_avg = (s2 + s4 + s6) / 3  # 오른쪽 평균

    # 1. 다리꼬기 — 좌우 압력 차이가 클 때
    if abs(left_avg - right_avg) > 200:
        return "다리꼬기"

    # 2. 거북목 — 앞쪽 압력이 뒤쪽보다 훨씬 높을 때
    if front_avg > 500 and front_avg - back_avg > 250:
        return "거북목"

    # 3. 기대기 — 뒤쪽 압력이 앞쪽보다 훨씬 높을 때
    if back_avg > 500 and back_avg - front_avg > 250:
        return "기대기"

    # 4. 바른자세 — 위 조건 다 아닐 때
    return "바른자세"


